import '../engine/core.dart';

Intent atk(int v, {int times = 1, String? s, int amt = 0, Elem e = Elem.none}) =>
    Intent(times > 1 ? IntentKind.attackMulti : IntentKind.attack,
        value: v, times: times, status: s, statusAmt: amt, elem: e);
Intent def(int v) => Intent(IntentKind.block, value: v);
Intent buff(String s, int v, {String? note}) =>
    Intent(IntentKind.buff, status: s, statusAmt: v, note: note);
Intent deb(String s, int v, {String? note}) =>
    Intent(IntentKind.debuff, status: s, statusAmt: v, note: note);
Intent special(String note, {int value = 0, String? s, int amt = 0}) =>
    Intent(IntentKind.special, value: value, status: s, statusAmt: amt, note: note);
Intent sleep() => const Intent(IntentKind.sleep, note: 'Dormant');

EnemyDef _e(String id, String name, int hp, int hpMax, Elem elem, int act,
        List<Intent> pattern,
        {int tier = 0, String? passive, String? passiveDesc, int pv = 0, String blurb = ''}) =>
    EnemyDef(
      id: id,
      name: name,
      hp: hp,
      hpMax: hpMax,
      elem: elem,
      tier: tier,
      act: act,
      pattern: pattern,
      passive: passive,
      passiveDesc: passiveDesc,
      passiveValue: pv,
      blurb: blurb,
      art: tier == 0 ? 'enemy_$id' : (tier == 1 ? 'elite_$id' : 'boss_$id'),
    );

