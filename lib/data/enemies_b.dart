/// The second bestiary. The first one shipped with three bosses per act, which
/// meant a player saw every boss in the game inside three runs. These bring
/// each act to eight, and widen the normal and elite pools to match.
///
/// Every passive named here is implemented in the battle engine — none of them
/// are decoration.
EnemyDef _e(String id, String name, int hp, int hpMax, Elem elem, int act,
        List<Intent> pattern,
        {int tier = 0, String? passive, String? passiveDesc, int pv = 0, String blurb = ''}) =>
    EnemyDef(
      id: id,
      name: name,
      hp: hp,
      hpMax: hpMax,
      elem: elem,
      tier: tier,
      act: act,
      pattern: pattern,
      passive: passive,
      passiveDesc: passiveDesc,
      passiveValue: pv,
      blurb: blurb,
      art: tier == 0 ? 'enemy_$id' : (tier == 1 ? 'elite_$id' : 'boss_$id'),
    );

